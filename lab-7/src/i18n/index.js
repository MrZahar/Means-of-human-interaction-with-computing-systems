function getInitialLanguage() {
    try {
        const value = window.localStorage.getItem('superhero-language');
        return value === 'en' || value === 'ru' ? value : 'ru';
    } catch {
        return 'ru';
    }
}

i18n.use(initReactI18next).init({
    resources,
    lng: getInitialLanguage(),
    fallbackLng: 'en',
    supportedLngs: ['ru', 'en'],
    interpolation: { escapeValue: false },
    react: { useSuspense: false }
});

function syncLanguage(language) {
    if (typeof document !== 'undefined') {
        document.documentElement.lang = language;
    }
    try {
        window.localStorage.setItem('superhero-language', language);
    } catch {
        // Private-browsing storage may be unavailable.
    }
}

i18n.on('languageChanged', syncLanguage);
syncLanguage(i18n.language);

export default i18n;
